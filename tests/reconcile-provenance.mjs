/* ════════════════════════════════════════════════════════════════════════
   tests/reconcile-provenance.mjs — READ-ONLY provenance reconcile REPORTER (SECTION-SCOPED-RUNS, #1)
   ────────────────────────────────────────────────────────────────────────
   The reconcile DANCE (read the settled manifestHash → decide export-inert vs real-output-change →
   hand-edit BUILD-MANIFEST.json + FIXTURE-PROVENANCE.json) is the biggest time/token sink in the
   re-bundle loop. This tool kills the *figuring-out* 90% of that cost WITHOUT touching a byte:

       node tests/reconcile-provenance.mjs               # report all 8 bundles
       node tests/reconcile-provenance.mjs --bundle=oxydex   # scope to one dex (same grammar as the gates)

   For each bundle it recomputes the CURRENT executed-code manifestHash (the same static projection the
   gates use), compares it to BUILD-MANIFEST.json, and — when they differ — inspects that bundle's
   fixtures to classify the change and print the EXACT edit to make. It emits three verdicts:

     • RECONCILED       current manifestHash == committed. Nothing to do. (Per CLAUDE.md: if the ledger
                        already reconciles, do NOT hand-edit it — you'd just race the concurrent writer.)
     • EXPORT-INERT     manifestHash MOVED but every committed fixture OUTPUT still hashes to its recorded
                        outputHash → the code change didn't move any export. Prints the BUILD-MANIFEST
                        manifestHash edit + the fixture manifestHash re-records (outputHash UNCHANGED).
                        It prints this ONLY when `tools/verify-fixtures.mjs --check` also reads every
                        fixture of the bundle as verified under the current `computeHash`.
     • VERIFICATION OWED  the outputs on disk match, but `computeHash` moved under ≥1 fixture whose
                        `verifiedUnder` names the old closure. Matching bytes on disk are NOT a re-run:
                        the fix is `node tools/verify-fixtures.mjs`, never a hand edit. Residue
                        2026-11-08-reconcile-calls-a-computehash-move-safe-to-hand-apply: Muse ran both
                        tools on one state, and this tool read EXPORT-INERT while verify-fixtures read 3
                        UNVERIFIED. This tool never read `computeHash` at all.
     • VERIFICATION UNREAD  verify-fixtures gave no PASS or FAIL (no corpus, a crash, an unreadable
                        verdict), so the tool cannot claim EXPORT-INERT and says so.
     • OUTPUT-MOVED     manifestHash moved AND ≥1 fixture output drifted → a real output change. Does NOT
                        print a hand-edit for the output: fixtures MUST be regenerated by RE-RUNNING the
                        app on its committed inputs and RE-EXPORTING (never hand-edited), then re-recorded.
                        Flags exactly which fixtures + reminds you the equiv/golden leg gates this.

   ⚠️ IT NEVER WRITES. By design (CLAUDE.md PROVENANCE-NONDETERMINISM §2/§4): the platform may rebuild a
   bundle and rewrite the ledgers OUT-OF-BAND, so an auto-writer would race that pipeline and could
   corrupt provenance. This tool only tells you the settled truth + the precise edit; a human/agent
   applies it deliberately AFTER the build settles. Re-run it right before you edit — if it now says
   RECONCILED, the other writer already synced; do nothing.

   Zero deps; shares manifest-gate.js with the gates, so its recompute is byte-identical to what
   verify-provenance.html / verify-manifest.mjs check. Exit 0 always (it's a report, not a gate).
   ════════════════════════════════════════════════════════════════════════ */
import { readFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { webcrypto } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { spawnSync } from 'node:child_process';

if (!globalThis.crypto) globalThis.crypto = webcrypto;

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const require = createRequire(import.meta.url);
const ManifestGate = require(join(ROOT, 'manifest-gate.js'));
// The schema name comes from verdict.js, so this READER of a verdict carries no schema literal of its own.
const VERDICT_SCHEMA = require(join(ROOT, 'verdict.js')).SCHEMA;

const C = { reset: '\x1b[0m', red: '\x1b[31m', green: '\x1b[32m', dim: '\x1b[2m', bold: '\x1b[1m', yellow: '\x1b[33m', cyan: '\x1b[36m' };
const paint = (s, c) => (process.stdout.isTTY ? c + s + C.reset : s);

// Scope filter (same grammar as the gates): --bundle=/--group=/first non-flag arg / env.
const FILTER = (() => {
  const a = process.argv.slice(2);
  for (let i = 0; i < a.length; i++) {
    const m = a[i].match(/^--?(?:bundle|group|only|b|g)=(.+)$/i);
    if (m) return m[1];
    if (/^--?(?:bundle|group|only|b|g)$/i.test(a[i]) && a[i + 1]) return a[i + 1];
    if (!a[i].startsWith('-')) return a[i];
  }
  return process.env.DEX_BUNDLE || process.env.DEX_GROUP || '';
})();
function matcher(filter) {
  if (!filter) return () => true;
  const tests = String(filter)
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((t) => {
      let rx = null;
      try {
        rx = new RegExp(t, 'i');
      } catch (_) {
        rx = null;
      }
      const lc = t.toLowerCase();
      return (s) => {
        s = String(s == null ? '' : s);
        return rx ? rx.test(s) : s.toLowerCase().indexOf(lc) >= 0;
      };
    });
  return (name) => tests.some((fn) => fn(name));
}

/* ── the verification read — one call to the tool that OWNS the answer ────────────────────────
   `tools/verify-fixtures.mjs --check --json` is the one place that decides whether a fixture's
   `verifiedUnder` matches its bundle's current `computeHash`. This tool reads that verdict
   rather than re-derive the rule, so the two can never disagree on which fixtures owe a re-run.
   Returns { status, unverified:Set } — status is the verdict's own, or 'UNREAD' with a reason. */
export function readVerification(run = spawnSync) {
  let r;
  try {
    r = run(process.execPath, [join(ROOT, 'tools', 'verify-fixtures.mjs'), '--check', '--json'], { cwd: ROOT, encoding: 'utf8' });
  } catch (e) {
    return { status: 'UNREAD', reason: 'verify-fixtures did not start: ' + e.message, unverified: new Set() };
  }
  let v = null;
  try {
    v = JSON.parse(String((r && r.stdout) || ''));
  } catch (_) {
    v = null;
  }
  if (!v || v.schema !== VERDICT_SCHEMA) return { status: 'UNREAD', reason: 'verify-fixtures printed no verdict (exit ' + (r && r.status) + ')', unverified: new Set() };
  if (v.status !== 'PASS' && v.status !== 'FAIL') return { status: 'UNREAD', reason: 'verify-fixtures read ' + v.status + (v.reason ? ': ' + v.reason : ''), unverified: new Set() };
  const list = (v.result && Array.isArray(v.result.unverified) && v.result.unverified) || [];
  return { status: v.status, reason: v.reason || null, unverified: new Set(list) };
}

/* The bundle's classification as a PURE function, so the selftest can drive every arm.
   EXPORT-INERT needs ALL THREE: no output moved, at least one output present, and verify-fixtures
   read every one of this bundle's fixtures as verified. */
export function classify({ moved, absent, total, owed, verification }) {
  if (moved > 0) return 'OUTPUT-MOVED';
  if (total > 0 && absent === total) return 'CANNOT CLASSIFY';
  if (verification !== 'PASS' && verification !== 'FAIL') return 'VERIFICATION UNREAD';
  if (owed > 0) return 'VERIFICATION OWED';
  return 'EXPORT-INERT';
}

async function main() {
  const _m = matcher(FILTER);
  const BUNDLES = FILTER ? ManifestGate.MANIFEST_BUNDLES.filter(_m) : ManifestGate.MANIFEST_BUNDLES;

  console.log(
    paint('Tepna reconcile-provenance', C.bold) +
      paint('  — READ-ONLY report (never writes)', C.dim) +
      (FILTER ? paint('  · filter "' + FILTER + '" → ' + BUNDLES.length + ' bundle(s)', C.yellow) : '')
  );
  if (FILTER && !BUNDLES.length) {
    console.log(paint('  filter matched ZERO bundles — check the pattern', C.red));
    return;
  }

  // committed ledgers — reassembled from the per-app provenance/ fragments (P3)
  let manifest, fixprov;
  try {
    const _led = require(join(ROOT, 'provenance-ledger.js')).loadNode({ readFileSync }, { join }, ROOT);
    manifest = _led.buildManifest;
    fixprov = _led.fixtureProvenance;
  } catch (e) {
    console.error(paint('✕ provenance/ ledger parse: ' + e.message, C.red));
    return;
  }
  const committed = (manifest && manifest.bundles) || {};
  const fixtures = (fixprov && fixprov.fixtures) || {};

  let anyAction = false;
  const VER = readVerification();
  if (VER.status === 'UNREAD') console.log(paint('  ⚠ verification state UNREAD — ' + VER.reason + '. No bundle can read EXPORT-INERT.', C.yellow));
  let anyOwed = false;

  for (const bundle of BUNDLES) {
    const p = join(ROOT, bundle);
    const committedMH = committed[bundle] && committed[bundle].manifestHash;
    if (!existsSync(p)) {
      console.log('\n' + paint('● ' + bundle, C.bold) + paint('  bundle file MISSING on disk — cannot recompute', C.red));
      anyAction = true;
      continue;
    }
    const currentMH = await ManifestGate.manifestHashFromText(readFileSync(p, 'utf8'));

    // fixtures produced by THIS bundle (code-gated only; historical snapshots aren't code-reproducible)
    const myFix = Object.keys(fixtures)
      .filter((k) => k[0] !== '_' && fixtures[k] && fixtures[k].bundle === bundle && !fixtures[k].historical)
      .map((k) => ({ name: k, rec: fixtures[k] }));

    const owedHere = myFix.filter((f) => VER.unverified.has(f.name));
    if (owedHere.length) anyOwed = true;
    if (currentMH === committedMH) {
      console.log('\n' + paint('● ' + bundle, C.bold) + '  ' + paint('✓ RECONCILED', C.green) + paint('  manifestHash ' + currentMH + ' — no ledger edit', C.dim));
      if (owedHere.length) {
        anyAction = true;
        console.log('  ' + paint('⟶ VERIFICATION OWED', C.red) + '  ' + owedHere.length + ' fixture(s) carry a verifiedUnder that is not the current computeHash:');
        for (const f of owedHere) console.log(paint('      • ' + f.name + '  verifiedUnder ' + (f.rec.verifiedUnder || '(none)'), C.yellow));
        console.log(paint('    Fix: node tools/verify-fixtures.mjs (it re-runs the suite on the corpus, then stamps). Never hand-edit verifiedUnder.', C.dim));
      }
      continue;
    }

    anyAction = true;
    console.log('\n' + paint('● ' + bundle, C.bold) + '  ' + paint('manifestHash MOVED', C.yellow) + paint('  committed ' + (committedMH || '(none)') + '  →  current ' + currentMH, C.dim));

    // classify: did any committed fixture OUTPUT change? (output-drift => real output change)
    let outMoved = [],
      outSame = [],
      outAbsent = [],
      outUnpinned = [];
    for (const f of myFix) {
      const outName = f.name; // fixtures keyed by the committed output file name
      const op = join(ROOT, 'uploads', outName);
      if (!existsSync(op)) {
        outAbsent.push(f);
        continue;
      }
      const outNow = await ManifestGate.sha16(new Uint8Array(readFileSync(op)));
      // DEEP-AUDIT-II §12.2 — mirror of the gateBEvaluate fix. `f.rec.outputHash && …` meant a record
      // carrying NO recorded output hash fell into `outSame` and was reported as "output unchanged",
      // asserting a comparison that never happened. Nothing pins those bytes, so it belongs with the
      // records needing attention, not the clean ones.
      if (!f.rec.outputHash) outUnpinned.push({ ...f, outNow });
      else if (outNow !== f.rec.outputHash) outMoved.push({ ...f, outNow });
      else outSame.push({ ...f, outNow });
    }

    const verdict = classify({ moved: outMoved.length, absent: outAbsent.length, total: myFix.length, owed: owedHere.length, verification: VER.status });
    if (outUnpinned.length) {
      console.log('  ' + paint('⟶ UNPINNED', C.red) + '  ' + outUnpinned.length + ' fixture record(s) carry NO outputHash — nothing pins those bytes.');
      console.log(paint('    A record with no outputHash cannot be reported as unchanged: there is nothing to compare against.', C.dim));
      for (const f of outUnpinned) console.log(paint('      • ' + f.name + '  (record the output hash: ' + f.outNow + ')', C.yellow));
    }
    if (outMoved.length) {
      console.log('  ' + paint('⟶ OUTPUT-MOVED', C.red) + '  ' + outMoved.length + ' fixture output(s) drifted — this is a REAL output change.');
      console.log(paint('    DO NOT hand-edit outputs. REGENERATE by re-running the app on its committed inputs and re-exporting,', C.dim));
      console.log(paint('    then re-record { manifestHash, inputHashes, outputHash } for each. The equiv/golden leg gates this.', C.dim));
      for (const f of outMoved) console.log(paint('      • ' + f.name + '  output ' + f.rec.outputHash + ' → ' + f.outNow + '  (regenerate; do not paste this hash)', C.yellow));
      if (outSame.length) console.log(paint('    (also re-record manifestHash on the same-output siblings below — same code moved them: ' + outSame.map((f) => f.name).join(', ') + ')', C.dim));
    } else if (verdict === 'CANNOT CLASSIFY') {
      console.log(
        '  ' +
          paint('⟶ CANNOT CLASSIFY', C.yellow) +
          '  all ' +
          myFix.length +
          ' fixture output(s) absent (uploads/ gitignored?). Re-run where uploads/ is served (the browser page) to classify inert vs moved.'
      );
    } else if (verdict === 'VERIFICATION UNREAD') {
      console.log('  ' + paint('⟶ VERIFICATION UNREAD', C.yellow) + '  the outputs on disk match, but verify-fixtures gave no verdict, so this is NOT read as export-inert.');
    } else if (verdict === 'VERIFICATION OWED') {
      console.log('  ' + paint('⟶ VERIFICATION OWED', C.red) + '  the outputs on disk match, but computeHash moved under ' + owedHere.length + ' fixture(s):');
      for (const f of owedHere) console.log(paint('      • ' + f.name + '  verifiedUnder ' + (f.rec.verifiedUnder || '(none)'), C.yellow));
      console.log(paint('    Matching bytes on disk are not a re-run. Fix: node tools/verify-fixtures.mjs. Do NOT apply the edits below by hand first.', C.dim));
    } else {
      console.log('  ' + paint('⟶ EXPORT-INERT', C.green) + '  every committed fixture output is unchanged, and verify-fixtures reads every fixture verified under the current computeHash.');
    }

    // The exact BUILD-MANIFEST edit (always needed once the hash moved and it's the settled value)
    console.log(paint('    EDIT BUILD-MANIFEST.json → bundles["' + bundle + '"].manifestHash:', C.cyan));
    console.log(paint('      "' + (committedMH || '') + '"  →  "' + currentMH + '"', C.bold));

    // Fixture manifestHash re-records (both inert siblings and moved ones carry the new code identity)
    const reRecord = outMoved.length ? myFix : outSame; // when output moved, ALL of this bundle's fixtures re-record
    if (reRecord.length) {
      console.log(
        paint(
          '    RE-RECORD FIXTURE-PROVENANCE.json fixtures[<name>].manifestHash → "' +
            currentMH +
            '"' +
            (outMoved.length
              ? '  (AND regenerate outputs first — see above)'
              : verdict === 'EXPORT-INERT'
                ? '  (outputHash UNCHANGED — inert):'
                : '  (outputs match on disk, but this is NOT read as inert — see above):'),
          C.cyan
        )
      );
      for (const f of reRecord) console.log(paint('      • ' + f.name + '   ' + (f.rec.manifestHash || '(none)') + ' → ' + currentMH, C.dim));
    }
  }

  console.log('\n' + paint('══════════════════════════════════════════', C.dim));
  if (anyOwed) console.log(paint('▸ VERIFICATION OWED on at least one bundle above — run node tools/verify-fixtures.mjs before any ledger edit.', C.red));
  if (!anyAction) console.log(paint('✓ ALL RECONCILED — no ledger edit needed (do NOT hand-edit a synced ledger).', C.green));
  else {
    console.log(paint('▸ Report only — NOTHING was written.', C.yellow) + paint('  Apply the edits above AFTER the build settles, then re-run this', C.dim));
    console.log(paint('  to confirm it now says RECONCILED. If it already flipped to RECONCILED, the concurrent writer synced it — do nothing.', C.dim));
    console.log(paint('  Verify with: node tests/verify-manifest.mjs' + (FILTER ? ' --bundle=' + FILTER : '') + '   (+ the equiv/golden leg in Dex-Test-Suite.html for OUTPUT-MOVED).', C.dim));
  }
}

/* ── selftest — every arm of classify(), and readVerification over scripted child results ── */
if (process.argv.includes('--selftest')) {
  let ran = 0,
    bad = 0;
  const eq = (got, want, m) => {
    ran++;
    if (got !== want) {
      bad++;
      console.error('SELFTEST FAIL: ' + m + ' — got ' + got + ', want ' + want);
    }
  };
  const base = { moved: 0, absent: 0, total: 3, owed: 0, verification: 'PASS' };
  eq(classify(base), 'EXPORT-INERT', 'clean outputs + PASS reads inert');
  eq(classify({ ...base, owed: 1, verification: 'FAIL' }), 'VERIFICATION OWED', 'THE ROW: matching outputs with one owed fixture is NOT inert');
  eq(classify({ ...base, verification: 'FAIL' }), 'EXPORT-INERT', 'a FAIL that names only other bundles leaves this bundle inert');
  eq(classify({ ...base, verification: 'UNREAD' }), 'VERIFICATION UNREAD', 'no verdict never reads inert');
  eq(classify({ ...base, verification: 'NOT_RUN' }), 'VERIFICATION UNREAD', 'a NOT_RUN verdict never reads inert');
  eq(classify({ ...base, moved: 1, owed: 2 }), 'OUTPUT-MOVED', 'a moved output outranks an owed stamp');
  eq(classify({ ...base, absent: 3 }), 'CANNOT CLASSIFY', 'all outputs absent cannot classify');
  const fake =
    (stdout, status = 0) =>
    () => ({ stdout, status });
  const vd = (status, unverified) => JSON.stringify({ schema: VERDICT_SCHEMA, status, result: { unverified } });
  let r = readVerification(fake(vd('FAIL', ['a.json', 'b.json']), 1));
  eq(r.status + ':' + [...r.unverified].join(','), 'FAIL:a.json,b.json', 'a FAIL verdict yields its unverified names');
  eq(readVerification(fake(vd('PASS', []))).status, 'PASS', 'a PASS verdict reads PASS');
  eq(readVerification(fake(vd('NOT_RUN', null))).status, 'UNREAD', 'NOT_RUN reads UNREAD');
  eq(readVerification(fake('not json', 2)).status, 'UNREAD', 'garbage stdout reads UNREAD');
  eq(
    readVerification(() => {
      throw new Error('boom');
    }).status,
    'UNREAD',
    'a spawn that throws reads UNREAD'
  );
  console.log('selftest: ' + (ran - bad) + '/' + ran + ' ok');
  process.exit(bad ? 1 : 0);
}

main();
